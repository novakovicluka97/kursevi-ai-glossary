/*
 * build-search-index.js
 * Generates js/search-index.js from the topic HTML files.
 *
 * Run this whenever topics are added or their content changes:
 *   node build-search-index.js
 *
 * It scans every file in topics/, extracts the title, definition,
 * section headings and body text, then writes a JS file that
 * defines window.SEARCH_INDEX for the client-side search.
 */

const fs = require('fs');
const path = require('path');

const TOPICS_DIR = path.join(__dirname, 'topics');
const OUTPUT = path.join(__dirname, 'js', 'search-index.js');

// Decode the handful of HTML entities that appear in this site.
function decodeEntities(s) {
  return s
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&rsaquo;/g, '>')
    .replace(/&rarr;/g, '->')
    .replace(/&nbsp;/g, ' ');
}

// Strip all HTML tags and collapse whitespace.
function stripTags(html) {
  return decodeEntities(html.replace(/<[^>]*>/g, ' '))
    .replace(/\s+/g, ' ')
    .trim();
}

// Pull the first capture group of a regex, or '' if no match.
function firstMatch(html, re) {
  const m = html.match(re);
  return m ? m[1] : '';
}

const files = fs
  .readdirSync(TOPICS_DIR)
  .filter((f) => f.endsWith('.html'))
  .sort();

const index = files.map((file) => {
  const html = fs.readFileSync(path.join(TOPICS_DIR, file), 'utf8');

  const title = stripTags(firstMatch(html, /<h1>([\s\S]*?)<\/h1>/));
  const definition = stripTags(
    firstMatch(html, /<p class="definition">([\s\S]*?)<\/p>/)
  );

  // Section headings give good keyword coverage without bloating the body.
  const headings = [];
  const headingRe = /<h2>([\s\S]*?)<\/h2>/g;
  let h;
  while ((h = headingRe.exec(html)) !== null) {
    headings.push(stripTags(h[1]));
  }

  // Body text: the explanatory prose only. We drop nav, scripts and
  // the "Related Topics" / "References" blocks so snippets show real
  // sentences instead of flattened link lists.
  let body = firstMatch(html, /<body>([\s\S]*?)<\/body>/);
  body = body
    .replace(/<nav[\s\S]*?<\/nav>/g, ' ')
    .replace(/<script[\s\S]*?<\/script>/g, ' ')
    .replace(/<style[\s\S]*?<\/style>/g, ' ')
    .replace(/<div class="related-topics">[\s\S]*?<\/div>/g, ' ')
    .replace(/<div class="references">[\s\S]*?<\/div>/g, ' ');
  const text = stripTags(body);

  return {
    url: 'topics/' + file,
    title,
    definition,
    headings,
    text,
  };
});

const banner =
  '/* AUTO-GENERATED by build-search-index.js — do not edit by hand.\n' +
  '   Regenerate with: node build-search-index.js */\n';

fs.writeFileSync(
  OUTPUT,
  banner + 'window.SEARCH_INDEX = ' + JSON.stringify(index, null, 0) + ';\n',
  'utf8'
);

console.log('Wrote ' + OUTPUT + ' with ' + index.length + ' topics.');
